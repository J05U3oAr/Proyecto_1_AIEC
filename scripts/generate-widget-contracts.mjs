import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Frontend-only adapter. The published schemas remain owned by M1.
const root = new URL('../', import.meta.url);
const names = ['chat-request', 'chat-response'];
const definitions = new Map();
const documents = names.map(name => {
  const schema = JSON.parse(readFileSync(new URL(`shared/contracts/v1/${name}.schema.json`, root)));
  for (const [key, value] of Object.entries(schema.$defs ?? {})) {
    if (definitions.has(key) && JSON.stringify(definitions.get(key)) !== JSON.stringify(value)) {
      throw new Error(`Conflicting definition: ${key}`);
    }
    definitions.set(key, value);
  }
  return schema;
});

function typeOf(schema) {
  if (schema.$ref) return schema.$ref.replace('#/$defs/', '');
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' | ');
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `Array<${typeOf(schema.items)}>`;
    case 'object':
      return `{\n${Object.entries(schema.properties)
        .map(
          ([key, value]) =>
            `  ${key}${schema.required?.includes(key) ? '' : '?'}: ${typeOf(value)};`
        )
        .join('\n')}\n}`;
    default:
      throw new Error('Unsupported schema type');
  }
}

const output =
  '// Generated by node scripts/generate-widget-contracts.mjs. Do not edit.\n' +
  [...definitions, ...documents.map(schema => [schema.title, schema])]
    .map(([name, schema]) => `export type ${name} = ${typeOf(schema)};\n`)
    .join('\n');
const destination = new URL('src/services/contracts.generated.ts', root);
if (process.argv.includes('--check')) {
  // Formatting and Windows line endings do not change the generated type contract.
  const normalize = value => value.replace(/\s/g, '').replace(/'/g, '"');
  if (normalize(readFileSync(destination, 'utf8')) !== normalize(output)) {
    throw new Error('Frontend types are stale: regenerate widget contracts');
  }
  console.log('Widget types match the published schemas.');
} else {
  writeFileSync(fileURLToPath(destination), output);
}
